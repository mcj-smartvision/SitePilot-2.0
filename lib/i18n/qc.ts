export function getQcMessages(locale: FormLocale): typeof EN {
  if (locale === 'fa' || locale === 'ar') return FA as typeof EN
  return EN
}

export function qcAiLabels(t: QcMessages): AiDraftLabels {
  return {
    draftByAi: t.draftByAi,
    confirmed: t.confirmed,
    approveSend: t.approveIssue,
    editText: t.editText,
    reject: t.reject,
    saving: t.saving,
  }
}

